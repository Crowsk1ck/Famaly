import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';

const app=readFileSync(new URL('../public/app.js',import.meta.url),'utf8');
const worker=readFileSync(new URL('../worker/index.js',import.meta.url),'utf8');
const css=readFileSync(new URL('../public/style.css',import.meta.url),'utf8');

test('only leadership sees oversight and it displays all six departments',()=>{
 assert.match(app,/id:'leadership',text:'Контроль керівників'/);
 assert.match(app,/n.id==='leadership'&&!\['leader','deputy'\].includes\(state.user.role\)/);
 assert.match(app,/case'leadership':content=await leadershipDashboard\(\);break/);
 assert.match(app,/api\('\/leadership-overview'\)/);
 assert.match(app,/x.head_active/);
 assert.match(app,/x.goals_met/);
});

test('department weekly report is autogenerated and can be submitted by appointed head',()=>{
 assert.match(app,/id:'report',title:'Тижневий звіт'/);
 assert.match(app,/case 'submit-weekly-report'/);
 assert.match(app,/case 'weekly-report-submit-form'/);
 assert.match(app,/api\('\/department-weekly-report','POST'/);
 assert.match(worker,/function completedReportWeek\(\)/);
 assert.match(worker,/function departmentWeekSnapshot\(/);
 assert.match(worker,/weeklyReportRecordId\(/);
 assert.match(worker,/user.role!=='head'\|\|!user.head_appointed/);
 assert.match(worker,/INSERT OR IGNORE INTO records/);
 assert.match(worker,/department_weekly/);
});

test('weekly operational reports cannot change payouts or be manually edited',()=>{
 assert.match(worker,/amount,starts_at,ends_at,evidence,extra,created_at,updated_at/);
 assert.match(worker,/record\.amount|,0,/m);
 assert.match(worker,/parseJson\(old.extra,\{\}\).kind==='department_weekly'/);
 assert.doesNotMatch(app,/weekly-report-pay|weekly-report-ledger/);
 assert.match(css,/\.gr-leader-grid/);
 assert.match(css,/@media\(max-width:680px\)/);
});
